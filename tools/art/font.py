def measure(text, face, scale=1, track=1):
    """Width in pixels of `text` rendered at `scale` with `track` source-pixels between glyphs."""
    total = 0
    for i, ch in enumerate(text):
        g = face.get(ch)
        if g is None:
            continue
        total += len(g[0]) * scale
        if i < len(text) - 1:
            total += track * scale
    return total


def draw(canvas, text, x, y, face, color, scale=1, track=1, shadow=None, shadow_off=(1, 1)):
    """Stamp `text` with its top-left at (x, y). Returns the x just past the last glyph.

    `color` may be a single hex or a list of hex, one per source row, so a wordmark can carry a
    vertical gradient without inventing colours outside the contract.
    """
    cx = x
    for i, ch in enumerate(text):
        g = face.get(ch)
        if g is None:
            continue
        gw = len(g[0])
        if shadow is not None:
            for ry, row in enumerate(g):
                for rx, cell in enumerate(row):
                    if cell != "#":
                        continue
                    for sy in range(scale):
                        for sx in range(scale):
                            canvas.set(cx + rx * scale + sx + shadow_off[0],
                                       y + ry * scale + sy + shadow_off[1], shadow)
        for ry, row in enumerate(g):
            col = color[ry] if isinstance(color, list) else color
            for rx, cell in enumerate(row):
                if cell != "#":
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        canvas.set(cx + rx * scale + sx, y + ry * scale + sy, col)
        cx += (gw + track) * scale
    return cx


def outline(canvas, text, x, y, face, color, scale=1, track=1, diagonal=True):
    """Paint a 1px halo around the glyph mass. Used for the wordmark only - the contract bans
    outlines on actors, but a title is signage, not an actor."""
    mask = set()
    cx = x
    for ch in text:
        g = face.get(ch)
        if g is None:
            continue
        for ry, row in enumerate(g):
            for rx, cell in enumerate(row):
                if cell != "#":
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        mask.add((cx + rx * scale + sx, y + ry * scale + sy))
        cx += (len(g[0]) + track) * scale
    steps = [(-1, 0), (1, 0), (0, -1), (0, 1)]
    if diagonal:
        steps += [(-1, -1), (1, -1), (-1, 1), (1, 1)]
    for (px, py) in mask:
        for (dx, dy) in steps:
            n = (px + dx, py + dy)
            if n not in mask:
                canvas.set(n[0], n[1], color)
