def render_cell(palette, rows):
    """One cell, its drawing centred, on a transparent 16 x 16."""
    im = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
    if not rows:
        return im
    h = len(rows)
    w = max(len(r) for r in rows)
    if w > CELL or h > CELL:
        raise ValueError("debris drawing larger than its cell: %dx%d" % (w, h))
    ox = (CELL - w) // 2
    oy = (CELL - h) // 2
    px = im.load()
    for y, line in enumerate(rows):
        for x, ch in enumerate(line):
            if ch == ".":
                continue
            if ch not in palette:
                raise ValueError("no colour for %r" % ch)
            c = palette[ch]
            px[ox + x, oy + y] = (int(c[1:3], 16), int(c[3:5], 16), int(c[5:7], 16), 255)
    return im


def check_palette():
    """Nothing reserved, nothing from a player pigment row: the two rules a debris cell could break."""
    reserved = {B.RIM.upper(), B.AMBIENT.upper()}
    pigment = set()
    for name in ("ember", "azure", "amber", "verdant"):
        pigment |= {c.upper() for c in M[name]}
    problems = []
    for name, palette, rows in CELLS:
        used = {ch for line in rows for ch in line if ch != "."}
        for ch in used:
            if ch not in palette:
                problems.append("%s draws %r, which its palette does not have" % (name, ch))
                continue
            c = palette[ch].upper()
            if c in reserved:
                problems.append("%s uses the reserved %s" % (name, c))
            if c in pigment:
                problems.append("%s wears player pigment %s" % (name, c))
    return problems


def build():
    rows_needed = (len(CELLS) + COLUMNS - 1) // COLUMNS
    sheet = Image.new("RGBA", (COLUMNS * CELL, rows_needed * CELL), (0, 0, 0, 0))
    for i, (_name, palette, rows) in enumerate(CELLS):
        sheet.alpha_composite(render_cell(palette, rows), ((i % COLUMNS) * CELL, (i // COLUMNS) * CELL))
    d = os.path.dirname(OUT)
    if not os.path.isdir(d):
        os.makedirs(d)
    sheet.save(OUT)
    return sheet


def preview(sheet):
    if not os.path.isdir(PREVIEW_DIR):
        os.makedirs(PREVIEW_DIR)
    zoom = 8
    # On the Castle floor's stone, the ground every one of these has to read against.
    bg = Image.new("RGBA", sheet.size, (0x1E, 0x26, 0x34, 255))
    bg.alpha_composite(sheet)
    big = bg.resize((sheet.width * zoom, sheet.height * zoom), Image.NEAREST)
    path = os.path.join(PREVIEW_DIR, "debris.png")
    big.convert("RGB").save(path)
    return path


def main():
    problems = check_palette()
    if problems:
        for p in problems:
            print("   " + p)
        raise SystemExit("boss_deaths.py: palette rules broken")
    sheet = build()
    print("   boss death debris: %d cells -> %s" % (len(CELLS), os.path.relpath(OUT, ROOT).replace(os.sep, "/")))
    return sheet


if __name__ == "__main__":
    print("preview: " + preview(main()))
