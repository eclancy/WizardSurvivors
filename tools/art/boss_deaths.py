# -*- coding: utf-8 -*-
"""What the bosses leave when they fall: the debris atlas BossDeath throws.

Run: python tools/art/boss_deaths.py      -> assets/bonelight/effects/boss-death-debris.png
                                            and a x8 look at it in tools/art/_boss_deaths/ (gitignored)

"Bosses should have cool death animations that relate to what they are" (2026-10-28). Each boss's
fall is written in its own class (scripts/BossEnemy.cs and the chapter boss subclasses) and played on
scripts/BossDeath.cs, which cuts the BODY out of the boss's own sheet - so nothing here redraws a
boss. This is only what comes off them: Elderbark's dead leaves and the bones it had grown over, the
Gaoler's keys and chains, the Archivist's pages, the Still Warden's ice, the Hayward's straw, chips
of the Ninth Stone. One atlas, 16 x 16 cells, eight to a row, in the order BossDeath.Cell names them.

WHY ITS OWN SHEET AND NOT A STRIP ON EACH BOSS'S. The boss sheets are regenerated by other passes
(the shared shading is being retuned as this is written), and a death strip on them would be a
merge conflict every time either moved. Debris is a different kind of art anyway: it is thrown,
lands, and is seen at every quarter turn, so it is drawn small and readable from any side.

THE CONTRACT, held as it is for any actor (.ai/art-direction.md):
  * Material rows only, and the boss's own: bark is stone and moss is lichen because Elderbark is
    (sprite_treant.py), the Gaoler's keys are gold and his chains steel, the Archivist's pages are
    bone with his violet in them. No new colour; nothing in a player pigment row.
  * The key light from the upper left: every piece is lit on its top-left edges and shaded on its
    bottom-right, in whatever quarter turn BossDeath throws it - it turns the sprite, not the light,
    which at this size reads as tumbling rather than as wrong.
  * No rim: the rim is for actors, and debris is not one. No occ contact line either; a piece that
    has landed is under every actor already (BossDeath draws landed debris at z -15).
  * The ELEMENTS ARE EMISSIVE: ice shards are the ice ramp with a white-hot core, a Warden of the
    Deep's broken plate glows fire along the break. Those are the only bright pixels on the sheet.
  * Small. A boss is 80 px of figure on a 96 cell; a key is twelve, a leaf seven. At x2 that is a
    leaf the size of a basic enemy's hand, which is what a leaf off a tree that size should be.
"""
