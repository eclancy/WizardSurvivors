# -*- coding: utf-8 -*-
"""Pack every ground tile into one atlas: assets/bonelight/tiles/atlas.png + atlas.json.

Why: LevelTilePainter used to give each 48x48 tile PNG its own TileSetAtlasSource, so every tile
was its own texture. The Compatibility renderer batches consecutive draws only while they share a
texture, and the ground is random variants side by side - so nearly every visible cell of the
ground, overlay and detail layers was its own draw call: about 2,000 a frame on the phone's
portrait view, 95% of the frame's draw calls (.ai/performance.md). With all of them in one
texture, a TileMapLayer quadrant is one draw.

Nothing is redrawn: each tile's pixels are copied as they are. Each cell gets a one-pixel border
that repeats its own edge (an extrusion), so nearest sampling at a tile's edge can never pick up
its neighbour in the atlas - LevelTilePainter sets the source's margins and separation to match
and turns Godot's own texture padding off, which would otherwise read the whole atlas back from
the GPU at load to build a padded copy.

Run by tools/art/tiles.py and tools/art/ground_detail.py after they write their tiles, so the
atlas cannot fall behind them; or on its own:

    python tools/art/tile_atlas.py

A tile missing from the atlas is not an error at runtime - LevelTilePainter falls back to the old
one-texture source for it - but RegressionChecks warns, because that tile then costs a draw call.

Only the manifests under assets/bonelight are packed. The Sketchbook's paper (assets/kidsart)
stays in its own directory, as everything there does.
"""
from __future__ import print_function

import io
import json
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT_DIR = os.path.join(ROOT, "assets", "bonelight", "tiles")
MANIFESTS = [
    os.path.join(OUT_DIR, "tiles.json"),
    os.path.join(OUT_DIR, "detail", "detail.json"),
]

TILE = 48
PAD = 1               # extruded border on every side of every cell
STRIDE = TILE + 2 * PAD
COLUMNS = 32


def manifest_paths():
    paths = []
    seen = set()
    for manifest in MANIFESTS:
        if not os.path.isfile(manifest):
            print("tile_atlas: no %s - skipped" % os.path.relpath(manifest, ROOT))
            continue
        data = json.load(io.open(manifest, encoding="utf-8"))
        for frame in data.get("frames", []):
            p = frame.get("path")
            if not p or p in seen:
                continue
            seen.add(p)
            paths.append(p)
    return paths


def extrude(atlas, tile, x, y):
    """Paste tile at (x, y) and repeat its outermost pixels one further out on every side."""
    atlas.paste(tile, (x, y))
    w, h = tile.size
    atlas.paste(tile.crop((0, 0, w, 1)), (x, y - 1))
    atlas.paste(tile.crop((0, h - 1, w, h)), (x, y + h))
    atlas.paste(tile.crop((0, 0, 1, h)), (x - 1, y))
    atlas.paste(tile.crop((w - 1, 0, w, h)), (x + w, y))
    for (sx, sy, dx, dy) in ((0, 0, -1, -1), (w - 1, 0, w, -1), (0, h - 1, -1, h), (w - 1, h - 1, w, h)):
        atlas.putpixel((x + dx, y + dy), tile.getpixel((sx, sy)))


def main():
    paths = manifest_paths()
    if not paths:
        print("tile_atlas: no tiles to pack")
        return 1
    rows = (len(paths) + COLUMNS - 1) // COLUMNS
    atlas = Image.new("RGBA", (COLUMNS * STRIDE, rows * STRIDE), (0, 0, 0, 0))
    cells = []
    for i, p in enumerate(paths):
        src = os.path.join(ROOT, p.replace("/", os.sep))
        tile = Image.open(src).convert("RGBA")
        if tile.size != (TILE, TILE):
            print("tile_atlas: %s is %dx%d, not %dx%d - left out" % (p, tile.size[0], tile.size[1], TILE, TILE))
            continue
        col, row = i % COLUMNS, i // COLUMNS
        extrude(atlas, tile, col * STRIDE + PAD, row * STRIDE + PAD)
        cells.append('    "%s": [%d, %d]' % (p, col, row))

    atlas.save(os.path.join(OUT_DIR, "atlas.png"))
    manifest = ('{\n'
                '  "_comment": "Generated by tools/art/tile_atlas.py from tiles.json and detail/detail.json: '
                'every ground tile in one texture, so the tile layers batch. Each cell is %d px with a %d px '
                'extruded border; tiles maps a tile\'s path to its [column, row]. Never edit by hand.",\n'
                '  "tile": %d,\n  "padding": %d,\n  "tiles": {\n%s\n  }\n}\n'
                % (TILE, PAD, TILE, PAD, ",\n".join(cells)))
    io.open(os.path.join(OUT_DIR, "atlas.json"), "w", encoding="utf-8", newline="\n").write(manifest.decode("utf-8"))
    print("tile_atlas: %d tiles -> atlas.png %dx%d" % (len(cells), atlas.size[0], atlas.size[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
