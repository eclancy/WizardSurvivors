using Godot;
using WizardSurvivors.scripts;

public partial class ChestReward : PickupBase
{
	[Export] public string ItemId { get; set; } = ChestItemCatalog.RelicKey;
	[Export] public Texture2D ChestTexture { get; set; }

	/// <summary>
	/// Every chest in the world, for ChestPointer's off-screen bubbles. A list kept by enter and
	/// exit rather than a group query, because the pointer reads it every frame.
	/// </summary>
	public static readonly System.Collections.Generic.List<ChestReward> Live = new();

	/// <summary>True once collected: the lid is still opening, but there is nothing left to point at.</summary>
	public bool Opened { get; private set; }

	/// <summary>
	/// Seconds spent rising out of the ground as a ghost before it can be collected, or 0 for a chest
	/// that is simply there. A side event's reward uses it (SideEvent.Succeed): the chest a player
	/// earned by holding the grove used to appear in the frame the event ended, often under his feet
	/// where it opened at once, so the payout was never seen arriving at all.
	/// </summary>
	public float MaterialiseSeconds { get; set; }
	private float materialiseAge;
	private bool materialising;

	// Pale and cold while it is still a ghost - Arcane cyan's light end, not the reserved rim colour.
	private static readonly Color Ghost = new Color(0.72f, 0.90f, 1f, 0f);

	public override void _EnterTree() => Live.Add(this);

	public override void _ExitTree() => Live.Remove(this);

	// A chest is a deliberate reward, not a consumable to hoover up: it holds its spawn position
	// and waits for the player to walk into it, rather than flying to them like XP and health.
	public override void _Ready()
	{
		MagnetAttracted = false;
		base._Ready();
		SetupVisual();
		SetupCollision();
		if (string.IsNullOrWhiteSpace(ItemId))
			ItemId = ChestItemCatalog.GetRandomItem(new RandomNumberGenerator());
		if (MaterialiseSeconds > 0f)
		{
			// Not collectable until it is solid; _Ready is outside any physics callback, so these
			// can be written directly.
			materialising = true;
			Monitoring = false;
			Modulate = Ghost;
		}
	}

	public override void _Process(double delta)
	{
		base._Process(delta);
		if (!materialising)
			return;

		materialiseAge += (float)delta;
		float t = Mathf.Clamp(materialiseAge / MaterialiseSeconds, 0f, 1f);
		// First 60%: a translucent ghost that flickers as it rises out of the ground. Last 40%: it
		// takes on colour and weight and settles.
		const float GhostPart = 0.6f;
		if (t < GhostPart)
		{
			float g = t / GhostPart;
			float flicker = 0.82f + 0.18f * Mathf.Sin(materialiseAge * 31f);
			Modulate = new Color(Ghost, 0.55f * g * flicker);
		}
		else
		{
			float solid = (t - GhostPart) / (1f - GhostPart);
			Modulate = new Color(Ghost.R, Ghost.G, Ghost.B, 0.55f).Lerp(Colors.White, solid * solid);
		}
		if (chestSprite != null)
		{
			float rise = 1f - (1f - t) * (1f - t);
			chestSprite.Position = new Vector2(0f, Mathf.Lerp(14f, 0f, rise));
			float s = Mathf.Lerp(0.72f, 1f, rise) + (t > 0.85f ? 0.06f * Mathf.Sin((t - 0.85f) / 0.15f * Mathf.Pi) : 0f);
			chestSprite.Scale = new Vector2(s, s);
		}

		if (t >= 1f)
		{
			materialising = false;
			Modulate = Colors.White;
			Monitoring = true;
		}
	}

	private void SetupVisual()
	{
		var root = GetNodeOrNull<Node2D>("PlaceholderShape");
		if (root == null)
		{
			root = new Node2D { Name = "PlaceholderShape" };
			AddChild(root);
		}

		if (root.GetChildCount() > 0)
			return;

		// 16x16 source art. 3.0 -> ~48px on screen, clearly readable next to the 72px player
		// sprite without hiding it. Collision below is sized to match.
		if (ChestTexture != null)
		{
			root.AddChild(new Sprite2D { Texture = ChestTexture, Position = Vector2.Zero, Scale = new Vector2(1.0f, 1.0f) });
			return;
		}

		// A four-frame idle and a four-frame opening animation, generated by tools/art/props_fx.py.
		// The chest used to be a single static frame that simply vanished when collected.
		var frames = GD.Load<SpriteFrames>("res://scenes/resources/ChestRewardFrames.tres");
		if (frames == null)
		{
			Texture2D fallback = ResourceLoader.Load<Texture2D>("res://assets/bonelight/props/chest.png");
			root.AddChild(new Sprite2D { Texture = fallback, Position = Vector2.Zero, Scale = new Vector2(1.0f, 1.0f) });
			return;
		}

		chestSprite = new AnimatedSprite2D
		{
			Name = "ChestSprite",
			SpriteFrames = frames,
			Animation = "idle",
			Scale = new Vector2(1.0f, 1.0f)
		};
		root.AddChild(chestSprite);
		chestSprite.Play("idle");
	}

	private AnimatedSprite2D chestSprite;

	private void SetupCollision()
	{
		var collision = GetNodeOrNull<CollisionShape2D>("CollisionShape2D");
		if (collision == null)
		{
			collision = new CollisionShape2D
			{
				Name = "CollisionShape2D",
				Shape = new CircleShape2D { Radius = 22f }
			};
			AddChild(collision);
		}
		Monitoring = true;
		Monitorable = true;
		CollisionMask = 1;
	}

	protected override void OnPickedUp(Node playerNode)
	{
		if (Opened)
			return;
		Opened = true;
		// Generated and allowlisted from the start and never played: a chest opened in silence.
		SfxPlayer.Global(SfxCatalog.ChestOpen);
		if (playerNode is Player player)
		{
			var game = GetTree().CurrentScene as Node2DGame;
			if (game != null)
			{
				game.OpenChestSelectionMenu();
			}
			else
			{
				if (!string.IsNullOrWhiteSpace(ItemId))
					player.AddChestItem(ItemId);
				player.Heal(4);
				// Mirrors Node2DGame.OnChestItemSelected: this is the no-menu fallback path, and
				// Vaultguard should pay out on either.
				player.OnChestOpened();
			}
		}

		PlayOpenAnimationThenFree();
	}

	// Let the lid finish opening before the chest disappears. The pickup is already resolved by
	// this point, so nothing gameplay-relevant waits on the animation; collision is dropped so the
	// chest cannot be collected twice while it plays out.
	//
	// This runs inside body_entered, where Godot refuses to change Monitoring or Monitorable
	// ("Function blocked during in/out signal"), so both are deferred to the end of the frame.
	// Writing them directly never took effect anyway - it only logged two errors per chest.
	private void PlayOpenAnimationThenFree()
	{
		SetDeferred(Area2D.PropertyName.Monitoring, false);
		SetDeferred(Area2D.PropertyName.Monitorable, false);

		if (chestSprite == null || chestSprite.SpriteFrames?.HasAnimation("open") != true)
		{
			QueueFree();
			return;
		}

		chestSprite.Play("open");
		chestSprite.AnimationFinished += QueueFree;
	}
}
